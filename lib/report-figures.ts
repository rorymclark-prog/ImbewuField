// Report figures — the site's own saved data, drawn.
//
// WHY THIS EXISTS. The site report described a real piece of ground in pages of bullets and never
// once showed it: no plan of the site, no picture of when the rain comes against what the roof can
// catch, no sun or wind diagram, nothing for the soil, nothing for the order of work. Rory: "i want
// visuals enriched into the site report… must be visual as well".
//
// Every figure here is drawn by code from typed, saved values — the design canvas, the measured
// facts, the site's climate and soil record, and the app's own sun, wind, tank and phasing maths.
// Nothing is generated by an image model and nothing is read back out of report prose, so a figure
// can never show a tank, a tree or a number the farmer did not save. Three rules hold throughout:
//
//   1. ONE MATHS. Roof catch comes from lib/roof-runoff, storage from lib/tank-sizing, the sun from
//      lib/solar via lib/sector, bed numbering from lib/design-beds-bridge. A figure that computed
//      its own answer would be a second opinion printed beside the first.
//   2. MISSING STAYS MISSING. No builder invents a default: it returns null, or draws the gap and
//      says what to record. A soil value that is only a generic estimate is drawn as "not measured".
//   3. NEVER COLOUR ALONE. Solid means already there or measured; a dashed outline means planned or
//      modelled. Every mark is labelled, so the page still reads on a black-and-white printer.
//
// Output is an SVG string, because the report rasterises one drawing for both the screen (<img>)
// and the PDF (lib/report-visual-pdf.ts). Inside an <img> no web font loads — hence Arial.


/** Space-grouped thousands and a decimal point, built by hand: en-ZA's own formatter groups with
 *  U+00A0 (which the PDF's WinAnsi font drops) and writes a decimal comma the report text never uses. */
export function figureNumber(value: number, digits = 0): string {
  const [whole, fraction = ''] = value.toFixed(digits).split('.');
  const grouped = whole.replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  const kept = fraction.replace(/0+$/, '');
  return kept ? `${grouped}.${kept}` : grouped;
}
const px = (v: number) => Math.round(v * 10) / 10;
/** Arial averages a little over half an em per character; close enough to keep labels off each other. */
const textWidth = (value: string, size: number) => value.length * size * 0.56;
const clip = (value: string, max: number) => value.length > max ? `${value.slice(0, Math.max(1, max - 1)).trimEnd()}…` : value;

type TextOptions = { size?: number; anchor?: 'start' | 'middle' | 'end'; weight?: number; fill?: string; halo?: boolean };
type ShapeOptions = { fill?: string; stroke?: string; width?: number; dash?: string; opacity?: number; radius?: number };

/** A tiny string-building pen. One per figure, so <defs> ids never have to be globally unique. */
function pen() {
  const parts: string[] = [];
  const defs: string[] = [];
  const paint = (o: ShapeOptions) => `fill="${o.fill ?? 'none'}"${o.stroke ? ` stroke="${o.stroke}" stroke-width="${o.width ?? 1.5}"` : ''}${o.dash ? ` stroke-dasharray="${o.dash}"` : ''}${o.opacity !== undefined ? ` opacity="${o.opacity}"` : ''}`;
  return {
    raw: (value: string) => { parts.push(value); },
    def: (value: string) => { defs.push(value); },
    text: (x: number, y: number, value: string, o: TextOptions = {}) => {
      const halo = o.halo ? ' stroke="#ffffff" stroke-width="3.5" stroke-linejoin="round" paint-order="stroke"' : '';
      parts.push(`<text x="${px(x)}" y="${px(y)}" fill="${o.fill ?? TEXT}" font-family="${FONT}" font-size="${o.size ?? 15}" font-weight="${o.weight ?? 400}" text-anchor="${o.anchor ?? 'start'}"${halo}>${escapeXml(value)}</text>`);
    },
    rect: (x: number, y: number, w: number, h: number, o: ShapeOptions = {}) => { parts.push(`<rect x="${px(x)}" y="${px(y)}" width="${px(Math.max(0, w))}" height="${px(Math.max(0, h))}" rx="${o.radius ?? 0}" ${paint(o)}/>`); },
    circle: (cx: number, cy: number, r: number, o: ShapeOptions = {}) => { parts.push(`<circle cx="${px(cx)}" cy="${px(cy)}" r="${px(Math.max(0, r))}" ${paint(o)}/>`); },
    line: (x1: number, y1: number, x2: number, y2: number, o: ShapeOptions = {}) => { parts.push(`<path d="M${px(x1)} ${px(y1)}L${px(x2)} ${px(y2)}" stroke-linecap="round" ${paint({ stroke: INK, ...o, fill: 'none' })}/>`); },
    path: (d: string, o: ShapeOptions = {}) => { parts.push(`<path d="${d}" stroke-linejoin="round" stroke-linecap="round" ${paint(o)}/>`); },
    /** 45° hatch: the black-and-white way to say "this area is a different kind of thing". */
    hatch: (id: string, colour: string, gap = 7, width = 1.6) => { defs.push(`<pattern id="${id}" width="${gap}" height="${gap}" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="${gap}" height="${gap}" fill="#ffffff"/><path d="M0 0V${gap}" stroke="${colour}" stroke-width="${width}"/></pattern>`); return `url(#${id})`; },
    done: (height: number, width = W) => `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${Math.ceil(height)}" viewBox="0 0 ${width} ${Math.ceil(height)}">${defs.length ? `<defs>${defs.join('')}</defs>` : ''}<rect width="100%" height="100%" fill="#ffffff"/>${parts.join('')}</svg>`,
  };
}
type Pen = ReturnType<typeof pen>;

/** Wraps words to a pixel width; figures are read on phones, so no line may run off the drawing. */
function wrapText(value: string, size: number, maxWidth: number): string[] {
  const lines: string[] = [];
  let current = '';
  for (const word of value.split(/\s+/).filter(Boolean)) {
    const next = current ? `${current} ${word}` : word;
    if (current && textWidth(next, size) > maxWidth) { lines.push(current); current = word; } else current = next;
  }
  if (current) lines.push(current);
  return lines;
}


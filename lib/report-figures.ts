// ── 4. Sun, wind and slope ────────────────────────────────────────────────────────────────────

const sentence = (value: string) => value ? value.charAt(0).toUpperCase() + value.slice(1).toLowerCase() : value;
/** Compass bearing → point on a north-up drawing. */
const polar = (cx: number, cy: number, r: number, bearingDeg: number): [number, number] => { const a = (bearingDeg * Math.PI) / 180; return [cx + r * Math.sin(a), cy - r * Math.cos(a)]; };
/** An arc between two bearings, sweeping clockwise or anticlockwise, sampled every 3°. */
function arcPoints(cx: number, cy: number, r: number, fromDeg: number, sweepDeg: number, clockwise: boolean) {
  const out: Array<[number, number]> = [];
  const steps = Math.max(2, Math.ceil(sweepDeg / 3));
  for (let i = 0; i <= steps; i++) out.push(polar(cx, cy, r, fromDeg + (clockwise ? 1 : -1) * (sweepDeg * i) / steps));
  return out;
}
const pathOf = (points: Array<[number, number]>, close = false) => `M${points.map(([x, y]) => `${px(x)} ${px(y)}`).join('L')}${close ? 'Z' : ''}`;
/** A ring segment centred on a bearing: the shape of "it comes from somewhere in here". */
const wedgePath = (cx: number, cy: number, r0: number, r1: number, bearingDeg: number, halfWidthDeg: number) => pathOf([...arcPoints(cx, cy, r1, bearingDeg - halfWidthDeg, halfWidthDeg * 2, true), ...arcPoints(cx, cy, r0, bearingDeg + halfWidthDeg, halfWidthDeg * 2, false)], true);
function arrow(p: Pen, from: [number, number], to: [number, number], o: ShapeOptions & { head?: number } = {}) {
  const head = o.head ?? 9, a = Math.atan2(to[1] - from[1], to[0] - from[0]);
  const stop: [number, number] = [to[0] - Math.cos(a) * head * 0.8, to[1] - Math.sin(a) * head * 0.8];
  p.line(from[0], from[1], stop[0], stop[1], { stroke: o.stroke ?? INK, width: o.width ?? 2.4, dash: o.dash });
  p.path(pathOf([to, [to[0] - Math.cos(a - 0.42) * head * 1.5, to[1] - Math.sin(a - 0.42) * head * 1.5], [to[0] - Math.cos(a + 0.42) * head * 1.5, to[1] - Math.sin(a + 0.42) * head * 1.5]], true), { fill: o.stroke ?? INK });
}

/**
 * The permaculture sector drawing: where the sun travels in summer and in winter, where wind and
 * fire arrive from, and which way the ground falls. All of it comes from lib/sector — the model
 * the Design Studio's Sector sheet draws — so the two can never disagree.
 *
 * The NASA POWER seasonal wind means are deliberately NOT drawn. lib/sector demotes them because
 * the circular mean of a two-lobed wind rose points into the gap between the lobes, a direction
 * the wind never blows from. Only the sourced regional pattern (hatched: not measured here) and
 * the farmer's own observation (solid: seen on this ground) get a mark.
 */
export function sectorFigure(location: LocationData | null | undefined, facts: ReportSiteFacts | null | undefined, language = 'en'): ReportFigure | null {
  if (!location || !finite(location.lat) || !isValidEarthLatitude(location.lat)) return null;
  const model = deriveSectorModel(sectorSiteFromLocation(location), location.lat, finite(location.lon) ? location.lon : undefined);
  const t = translator(language);
  const p = pen();
  const cx = W / 2, cy = 276, R = 128;
  const side = (s: 'N' | 'S' | 'overhead') => s === 'S' ? t('to the south', 'eningizimu') : s === 'N' ? t('to the north', 'enyakatho') : t('overhead', 'phezulu ngqo');
  const { summer, winter } = model.solar;

  // The finding first: the low winter sun is what decides where shade falls when it matters most.
  p.text(14, 25, winter.noonSide === 'overhead' ? t('The midday sun stands almost overhead', 'Ilanga lasemini licishe libe phezulu ngqo') : `${t('The midday sun stands', 'Ilanga lasemini lima')} ${side(winter.noonSide)}`, { size: 17, weight: 700, fill: INK });
  const shadowOf = (path: typeof winter) => { if (!finite(path.shadowRatio) || path.shadowRatio <= 0.05) return ''; const n = figureNumber(path.shadowRatio, 1); return t(`a 1 m post throws a ${n} m shadow`, `isigxobo esingu-1 m senza isithunzi esingu-${n} m`); };
  p.text(14, 46, `${t('Winter', 'Ubusika')}: ${Math.round(winter.noonAltitudeDeg)}° ${t('above the horizon', 'ngaphezu komkhathizwe')}${shadowOf(winter) ? `, ${shadowOf(winter)}` : ''}   ·   ${t('Summer', 'Ihlobo')}: ${Math.round(summer.noonAltitudeDeg)}°`, { size: 13, fill: MUTED });

  p.circle(cx, cy, R, { fill: PAPER, stroke: HAIR, width: 1.5 });
  for (let b = 0; b < 360; b += 22.5) { const major = b % 90 === 0; const [x1, y1] = polar(cx, cy, R, b), [x2, y2] = polar(cx, cy, R - (major ? 9 : 5), b); p.line(x1, y1, x2, y2, { stroke: major ? MUTED : HAIR, width: major ? 1.6 : 1 }); }

  const described: string[] = [];
  const key: KeyEntry[] = [];
  const sunArc = (path: typeof summer, r: number, isWinter: boolean, name: string) => {
    if (!finite(path.sunriseAzDeg) || !finite(path.sunsetAzDeg)) return;
    const viaSouth = path.noonSide === 'S' || (path.noonSide === 'overhead' && !model.southernHemisphere);
    const sweep = viaSouth ? path.sunsetAzDeg - path.sunriseAzDeg : path.sunriseAzDeg + (360 - path.sunsetAzDeg);
    const points = arcPoints(cx, cy, r, path.sunriseAzDeg, sweep, viaSouth);
    p.path(pathOf(points), { stroke: AMBER, width: 7 });
    if (isWinter) p.path(pathOf(points), { stroke: '#ffffff', width: 2.4 });
    for (const end of [points[0], points[points.length - 1]]) p.circle(end[0], end[1], 5.5, { fill: '#ffffff', stroke: AMBER, width: 2.4 });
    const [lx, ly] = polar(cx, cy, r, viaSouth ? 180 : 0);
    p.text(lx, ly + (viaSouth ? -11 : 20), name, { size: 12, weight: 700, fill: INK, anchor: 'middle', halo: true });
    key.push({ draw: (x, y) => { p.line(x, y, x + 20, y, { stroke: AMBER, width: 7 }); if (isWinter) p.line(x, y, x + 20, y, { stroke: '#ffffff', width: 2.4 }); }, label: `${name}: ${t('rises', 'liphuma')} ${path.riseLabel16}, ${t('sets', 'lishona')} ${path.setLabel16}` });
    described.push(`${name}: ${t('rises', 'liphuma')} ${path.riseLabel16}, ${t('sets', 'lishona')} ${path.setLabel16}, ${Math.round(path.noonAltitudeDeg)}° ${t('above the horizon at midday', 'ngaphezu komkhathizwe emini')}, ${side(path.noonSide)}.`);
  };
  // Same convention as the Sector sheet: the short winter path sits inside the long summer one.
  sunArc(summer, 92, false, t('Summer sun', 'Ilanga lasehlobo'));
  sunArc(winter, 60, true, t('Winter sun', 'Ilanga lasebusika'));

  // Every wedge is drawn (and its outline remembered) before any label is placed, so a label can
  // step outward along its bearing until it clears all of them, the header and the other labels.
  const outline: Array<[number, number]> = [];
  const wedge = (r0: number, r1: number, bearingDeg: number, halfWidthDeg: number, o: ShapeOptions) => {
    p.path(wedgePath(cx, cy, r0, r1, bearingDeg, halfWidthDeg), o);
    outline.push(...arcPoints(cx, cy, r1, bearingDeg - halfWidthDeg, halfWidthDeg * 2, true), ...arcPoints(cx, cy, (r0 + r1) / 2, bearingDeg - halfWidthDeg, halfWidthDeg * 2, true));
  };
  const placed: Box[] = [];
  const outside = (bearingDeg: number, fromR: number, lines: Array<{ value: string; bold?: boolean }>) => {
    const b = ((bearingDeg % 360) + 360) % 360, octant = Math.round(b / 45) % 8;
    // Which corner of the label touches the bearing line: N hangs above, NE sits up-right, and so on.
    const hx = [0.5, 0, 0, 0, 0.5, 1, 1, 1][octant], hy = [1, 1, 0.5, 0, 0, 0, 0.5, 1][octant];
    const maxWidth = octant === 2 || octant === 6 ? 128 : octant === 0 || octant === 4 ? 200 : 186;
    // A line that will not fit breaks at its ' · ' joints first, and only then between words.
    const rows = lines.flatMap(line => (textWidth(line.value, 12) * (line.bold ? 1.08 : 1) <= maxWidth ? [line.value] : line.value.split(' · ')).flatMap(part => wrapText(part, 12, maxWidth / (line.bold ? 1.08 : 1))).map(value => ({ value, bold: line.bold })));
    const w = Math.max(...rows.map(r => textWidth(r.value, 12) * (r.bold ? 1.08 : 1))), h = rows.length * 15;
    let box: Box = { x: 0, y: 0, w, h };
    for (let r = fromR; r <= fromR + 96; r += 6) {
      const [ax, ay] = polar(cx, cy, r, b);
      box = { x: Math.min(W - 10 - w, Math.max(10, ax - w * hx)), y: ay - h * hy, w, h };
      const grown: Box = { x: box.x - 4, y: box.y - 4, w: w + 8, h: h + 8 };
      if (box.y >= 56 && !placed.some(other => overlaps(grown, other)) && !outline.some(([x, y]) => x > grown.x && x < grown.x + grown.w && y > grown.y && y < grown.y + grown.h)) break;
    }
    placed.push(box);
    const anchor = hx === 0 ? 'start' : hx === 1 ? 'end' : 'middle';
    rows.forEach((row, i) => p.text(box.x + w * hx, box.y + 11 + i * 15, row.value, { size: 12, weight: row.bold ? 700 : 400, fill: row.bold ? INK : MUTED, anchor, halo: true }));
  };

  const windHatch = model.namedWind.length ? p.hatch('wind', SLATE, 5, 1.3) : '';
  const fireHatch = model.fire ? p.hatch('fire', AMBER, 4, 1.5) : '';
  const sameBearing = (x: number, y: number) => Math.abs(((x - y + 540) % 360) - 180) < 12;
  if (model.fire) wedge(R + 27, R + 41, model.fire.bearingDeg, model.fire.halfWidthDeg, { fill: fireHatch, stroke: AMBER, width: 1.4, dash: '5 3' });
  for (const wind of model.namedWind) {
    wedge(R + 4, R + 25, wind.bearingDeg, wind.halfWidthDeg, { fill: windHatch, stroke: SLATE, width: 1.3, dash: '5 3' });
    arrow(p, polar(cx, cy, R + 25, wind.bearingDeg), polar(cx, cy, R - 4, wind.bearingDeg), { stroke: SLATE, width: 2, dash: '5 3', head: 7 });
  }
  for (const wind of model.namedWind) {
    const carriesFire = !!model.fire && sameBearing(model.fire.bearingDeg, wind.bearingDeg);
    outside(wind.bearingDeg, R + (carriesFire ? 47 : 31), [{ value: sentence(wind.title), bold: true }, { value: `${t('from the', 'uvela e')} ${wind.fromLabel} · ${wind.season}` }, ...(carriesFire ? [{ value: t('fire follows this wind', 'umlilo ulandela lo moya') }] : [])]);
    described.push(`${sentence(wind.title)}: ${t('from the', 'uvela e')} ${wind.fromLabel}, ${wind.season} (${t('regional pattern', 'iphethini yesifunda')}).`);
  }
  if (model.fire) {
    const fire = model.fire;
    if (!model.namedWind.some(w => sameBearing(fire.bearingDeg, w.bearingDeg))) outside(fire.bearingDeg, R + 47, [{ value: t('Fire risk', 'Ingozi yomlilo'), bold: true }, { value: `${t('from the', 'uvela e')} ${fire.fromLabel}` }]);
    described.push(`${t('Fire is most likely to arrive from the', 'Umlilo kungenzeka ufike uvela e')} ${fire.fromLabel}. ${fire.seasonNote}`);
  }
  const observed = labelToBearing(facts?.measurements?.localWindFrom);
  if (observed !== null) {
    const strongest = facts?.measurements?.localWindStrongestFrom;
    arrow(p, polar(cx, cy, R - 6, observed), polar(cx, cy, 30, observed), { stroke: INK, width: 3.4, head: 10 });
    described.push(`${t('Wind recorded on this site: usually from the', 'Umoya oqoshwe kule ndawo: uvame ukuvela e')} ${facts?.measurements?.localWindFrom}${strongest ? `; ${t('strongest from the', 'onamandla kakhulu uvela e')} ${strongest}` : ''}.`);
    key.push({ draw: (x, y) => arrow(p, [x, y], [x + 21, y], { stroke: INK, width: 3, head: 7 }), label: `${t('Wind you recorded here: from the', 'Umoya owuqophe lapha: uvela e')} ${facts?.measurements?.localWindFrom}${strongest ? ` (${t('strongest', 'onamandla')} ${strongest})` : ''}` });
  }
  if (model.water && !model.flat) {
    const water = model.water;
    arrow(p, polar(cx, cy, 14, water.downhillBearingDeg), polar(cx, cy, 48, water.downhillBearingDeg), { stroke: BLUE, width: 3, dash: water.indicative ? '5 3' : undefined, head: 8 });
    described.push(`${t('The ground falls toward the', 'Umhlaba wehlela e')} ${aspectLabel(water.downhillBearingDeg)} (${figureNumber(water.slopePct, 1)} % ${t('slope', 'umthambeka')}).`);
    key.push({ draw: (x, y) => arrow(p, [x, y], [x + 21, y], { stroke: BLUE, width: 3, dash: water.indicative ? '4 2' : undefined, head: 7 }), label: `${t('Downhill, toward the', 'Ukwehla, ngase')} ${aspectLabel(water.downhillBearingDeg)} (${figureNumber(water.slopePct, 1)} %)${water.indicative ? ` — ${t('check with a level', 'hlola ngelevela')}` : ''}` });
  } else {
    described.push(t('The ground reads as nearly flat, so no downhill direction is drawn.', 'Umhlaba ubonakala ucishe ube yisicaba, ngakho akukho ndlela yokwehla edwetshiwe.'));
    key.push({ draw: (x, y) => p.circle(x + 10, y, 5, { stroke: BLUE, width: 1.6, dash: '3 2' }), label: t('Nearly flat: no downhill direction drawn — check with a level', 'Cishe yisicaba: akukho ndlela yokwehla — hlola ngelevela') });
  }
  if (model.namedWind.length) key.push({ draw: (x, y) => p.rect(x + 1, y - 7, 18, 13, { fill: windHatch, stroke: SLATE, width: 1.3, dash: '4 2' }), label: t('Wind of the region — not measured on this site', 'Umoya wesifunda — awulinganiswanga kule ndawo') });
  if (model.fire) key.push({ draw: (x, y) => p.rect(x + 1, y - 7, 18, 13, { fill: fireHatch, stroke: AMBER, width: 1.3, dash: '4 2' }), label: t('Where fire is most likely to come from (regional)', 'Lapho umlilo ungavela khona (isifunda)') });

  // Compass letters last, so no wedge or arrow can cover them; the site sits at the centre.
  ([['N', 0], ['E', 90], ['S', 180], ['W', 270]] as const).forEach(([label, b]) => { const [x, y] = polar(cx, cy, R - 20, b); p.text(x, y + 5, label, { size: label === 'N' ? 16 : 13, weight: 700, fill: label === 'N' ? INK : MUTED, anchor: 'middle', halo: true }); });
  p.path(`M${cx - 8} ${cy + 7}V${cy - 2}L${cx} ${cy - 10}L${cx + 8} ${cy - 2}V${cy + 7}Z`, { fill: INK });

  const lowest = Math.max(cy + R, ...outline.map(([, y]) => y), ...placed.map(box => box.y + box.h));
  const height = keyRow(p, 14, lowest + 32, key) + 4;
  const lat = `${Math.abs(location.lat).toFixed(2)}° ${location.lat < 0 ? 'S' : 'N'}`;
  return {
    id: 'sectors', width: W, height: Math.ceil(height), svg: p.done(height),
    title: t('Sun, wind and slope', 'Ilanga, umoya nomthambeka'),
    note: t('North is up; the house mark is this site. Sun paths are calculated from the latitude. Hatched marks are regional patterns, not measurements: check them against what you and your neighbours see.', 'INyakatho iphezulu; uphawu lwendlu yile ndawo. Izindlela zelanga zibalwa ngokwe-latitude. Izimpawu ezinemidwa ziyiphethini yesifunda, aziyona imilinganiso: ziqinisekise ngalokho wena nomakhelwane enikubonayo.'),
    source: `${t('Sun: calculated for latitude', 'Ilanga: kubalwe nge-latitude')} ${lat}.${model.namedWind.length || model.fire ? ` ${t('Wind and fire: regional pattern', 'Umoya nomlilo: iphethini yesifunda')}${model.regionKey ? ` (${model.regionKey})` : ''}.` : ''}${model.water ? ` ${t('Slope: elevation model.', 'Umthambeka: imodeli yokuphakama.')}` : ''}${observed !== null ? ` ${t('Observed wind: recorded in the Design Studio.', 'Umoya obonwe: uqoshwe ku-Design Studio.')}` : ''}`,
    alt: `${t('Sector diagram', 'Umdwebo wamasekta')}. ${described.join(' ')}`,
  };
}

// ── 5. Soil ───────────────────────────────────────────────────────────────────────────────────

/**
 * pH, texture and organic carbon. The MARK carries the provenance: a filled dot is a laboratory
 * result from this ground, a hollow dot is the SoilGrids world model's estimate for the location,
 * and anything else — including the generic fallback values the app carries when no source
 * answered — is drawn as an empty scale marked "not measured". Same rule as lib/report-summary.
 */
export function soilFigure(location: LocationData | null | undefined, language = 'en'): ReportFigure | null {
  const soil = location?.soil;
  if (!soil) return null;
  const t = translator(language);
  const p = pen();
  const lab = soil.soilSource === 'lab', known = lab || soil.soilSource === 'soilgrids';
  const x0 = 40, x1 = W - 40;
  const marker = (x: number, y: number) => p.circle(x, y, 8, lab ? { fill: INK, stroke: '#ffffff', width: 2 } : { fill: '#ffffff', stroke: INK, width: 2.6 });
  const empty = (y: number) => { p.rect(x0, y - 7, x1 - x0, 14, { fill: '#ffffff', stroke: MUTED, width: 1.2, dash: '5 4', radius: 7 }); p.text((x0 + x1) / 2, y + 4.5, t('not measured', 'akulinganiswanga'), { size: 12, fill: MUTED, anchor: 'middle' }); };
  let y = 24;

  // pH
  p.text(14, y, t('How sour or sweet the soil is (pH)', 'Ukuthi umhlabathi umuncu noma umnandi kangakanani (pH)'), { size: 14, weight: 700, fill: INK });
  const phY = y + 42, phOf = (v: number) => x0 + ((v - 4) / 5) * (x1 - x0);
  const ph = known && finite(soil.ph) && soil.ph >= 3 && soil.ph <= 10 ? soil.ph : null;
  if (ph !== null) {
    p.rect(x0, phY - 7, x1 - x0, 14, { fill: TRACK, radius: 7 });
    p.rect(phOf(6), phY - 7, phOf(7) - phOf(6), 14, { fill: p.hatch('veg', GREEN, 5, 1.3), stroke: GREEN, width: 1.2 });
    marker(phOf(Math.min(9, Math.max(4, ph))), phY);
    p.text(phOf(Math.min(9, Math.max(4, ph))), phY - 15, `pH ${figureNumber(ph, 1)}`, { size: 14, weight: 700, fill: INK, anchor: 'middle', halo: true });
  } else empty(phY);
  for (let v = 4; v <= 9; v++) { p.line(phOf(v), phY + 9, phOf(v), phY + 14, { stroke: MUTED, width: 1 }); p.text(phOf(v), phY + 28, String(v), { size: 12, fill: MUTED, anchor: 'middle' }); }
  p.text(x0, phY + 46, t('← more acid (sour)', '← umuncu kakhulu'), { size: 12, fill: MUTED });
  p.text(x1, phY + 46, t('more alkaline →', 'une-alkali kakhulu →'), { size: 12, fill: MUTED, anchor: 'end' });
  if (ph !== null) p.text((phOf(6) + phOf(7)) / 2, phY + 46, t('most vegetables: 6 to 7', 'imifino eminingi: 6 kuya ku-7'), { size: 12, fill: GREEN, weight: 700, anchor: 'middle' });
  y = phY + 78;

  // Texture
  const parts = [{ name: t('Sand', 'Isihlabathi'), value: soil.sand }, { name: t('Silt', 'Udaka olucolekile'), value: soil.silt }, { name: t('Clay', 'Ubumba'), value: soil.clay }];
  const total = parts.reduce((sum, part) => sum + (finite(part.value) ? part.value : NaN), 0);
  const textureOk = known && Number.isFinite(total) && total > 90 && total < 110 && parts.every(part => (part.value as number) >= 0);
  p.text(14, y, `${t('What the soil is made of', 'Ukuthi umhlabathi wenziwe ngani')}${textureOk && soil.textureClass ? `: ${soil.textureClass}` : ''}`, { size: 14, weight: 700, fill: INK });
  const barY = y + 16;
  if (textureOk) {
    const looks: ShapeOptions[] = [{ fill: '#f5eadc', stroke: AMBER }, { fill: p.hatch('silt', SLATE, 6, 1.2), stroke: SLATE }, { fill: AMBER, stroke: AMBER }];
    let x = x0;
    parts.forEach((part, i) => {
      const w = ((part.value as number) / total) * (x1 - x0);
      p.rect(x + 1, barY, Math.max(0, w - 2), 26, { ...looks[i], width: 1.4, dash: lab ? undefined : '5 3', radius: 3 });
      const label = `${part.name} ${Math.round(part.value as number)} %`;
      if (w > textWidth(label, 12.5) + 12) p.text(x + w / 2, barY + 44, label, { size: 12.5, weight: 700, fill: INK, anchor: 'middle' });
      else p.text(x + w / 2, barY + 44, `${Math.round(part.value as number)} %`, { size: 12, fill: INK, anchor: 'middle' });
      x += w;
    });
  } else empty(barY + 13);
  y = barY + 78;

  // Organic carbon
  p.text(14, y, t('Organic carbon: how much rotted plant matter the soil holds', 'Ikhabhoni yemvelo: ukuthi umhlabathi uphethe izinto zezitshalo ezibolile ezingakanani'), { size: 14, weight: 700, fill: INK });
  const ocY = y + 42, ocOf = (v: number) => x0 + (v / 5) * (x1 - x0);
  const oc = known && finite(soil.organicCarbon) && soil.organicCarbon >= 0 ? soil.organicCarbon : null;
  if (oc !== null) {
    p.rect(x0, ocY - 7, x1 - x0, 14, { fill: TRACK, radius: 7 });
    marker(ocOf(Math.min(5, oc)), ocY);
    p.text(ocOf(Math.min(5, oc)), ocY - 15, `${figureNumber(oc, 1)} %`, { size: 14, weight: 700, fill: INK, anchor: 'middle', halo: true });
  } else empty(ocY);
  for (let v = 0; v <= 5; v++) { p.line(ocOf(v), ocY + 9, ocOf(v), ocY + 14, { stroke: MUTED, width: 1 }); p.text(ocOf(v), ocY + 28, `${v}${v === 5 ? '+' : ''} %`, { size: 12, fill: MUTED, anchor: 'middle' }); }
  y = ocY + 52;

  p.line(14, y, W - 14, y, { stroke: HAIR, width: 1 });
  y += 24;
  if (known) { marker(24, y - 4); y = paragraph(p, 42, y, lab ? t('Filled dot: measured by a laboratory on a sample from this site.', 'Ichashazi eligcwele: kulinganiswe yilabhorethri kusampula yale ndawo.') : t('Hollow dot and dashed outlines: estimated for this location by the SoilGrids world soil model, not measured here. A soil test on your own sample will replace them.', 'Ichashazi elingenalutho nemidwa enqamukayo: kulinganiselwe le ndawo yimodeli yomhlabathi yomhlaba i-SoilGrids, akulinganiswanga lapha. Ukuhlolwa komhlabathi wakho kuzokuvala lokhu.'), W - 56, { size: 12.5 }); }
  else y = paragraph(p, 14, y, t('No soil measurement is recorded for this site, so nothing is plotted. Arrange a soil test: the result fills in all three scales.', 'Akukho ukulinganiswa komhlabathi okuqoshiwe kule ndawo, ngakho akukho okudwetshiwe. Hlela ukuhlolwa komhlabathi: umphumela uzogcwalisa zonke izikali ezintathu.'), W - 28, { size: 13, weight: 700, fill: INK });

  return {
    id: 'soil', width: W, height: Math.ceil(y + 4), svg: p.done(y + 4),
    title: t('Soil at a glance', 'Umhlabathi ngamafuphi'),
    note: t('Top 30 cm of soil. No "good" or "bad" bands are drawn for organic carbon because the right level depends on the soil type and climate.', 'Amasentimitha angu-30 aphezulu omhlabathi. Ayikho imigqa ethi "kuhle" noma "kubi" yekhabhoni yemvelo ngoba izinga elifanele lincike ohlotsheni lomhlabathi nesimo sezulu.'),
    source: lab ? t('Your uploaded laboratory soil test', 'Ukuhlolwa kwakho komhlabathi kwelabhorethri okulayishiwe') : known ? t('SoilGrids world soil model (ISRIC), 250 m grid: an estimate, not a measurement', 'Imodeli yomhlabathi yomhlaba i-SoilGrids (ISRIC), igridi engu-250 m: isilinganiso, akusona isilinganiso sangempela') : t('No soil measurement recorded', 'Akukho ukulinganiswa komhlabathi okuqoshiwe'),
    alt: known ? `${t('Soil', 'Umhlabathi')}: ${ph !== null ? `pH ${figureNumber(ph, 1)}; ` : ''}${textureOk ? `${parts.map(part => `${part.name} ${Math.round(part.value as number)} %`).join(', ')}; ` : ''}${oc !== null ? `${t('organic carbon', 'ikhabhoni yemvelo')} ${figureNumber(oc, 1)} %` : ''} (${lab ? t('laboratory result', 'umphumela welabhorethri') : t('SoilGrids estimate', 'isilinganiso se-SoilGrids')}).` : t('Soil not measured.', 'Umhlabathi awulinganiswanga.'),
  };
}

// ── 6. Order of work ──────────────────────────────────────────────────────────────────────────

/**
 * lib/phasing's build phases as bars on a weeks axis. Coarse on purpose: phases and hold points,
 * no task-level dependency arrows — the plan is a sequence to agree on, not a project schedule.
 * Every bar is work still to do, so every bar wears the "planned" look (tint, dashed outline).
 */
export function timelineFigure(plan: PhasePlan | null | undefined, language = 'en'): ReportFigure | null {
  const phases = plan?.phases ?? [];
  if (phases.length < 2 || !phases.every(ph => finite(ph.weekStart) && finite(ph.weekEnd) && ph.weekEnd >= ph.weekStart)) return null;
  const t = translator(language);
  const p = pen();
  const left = 22, right = W - 30;
  const last = phases[phases.length - 1];
  const maxWeek = Math.max(...phases.map(ph => ph.weekEnd), 1);
  const step = maxWeek <= 12 ? 1 : maxWeek <= 24 ? 2 : maxWeek <= 48 ? 4 : 8;
  const xOf = (week: number) => left + (week / maxWeek) * (right - left);
  const rowH = 46, top = 16, bottom = top + phases.length * rowH;
  for (let w = 0; w <= maxWeek; w += step) p.line(xOf(w), top, xOf(w), bottom + 4, { stroke: HAIR, width: 1 });
  phases.forEach((phase, i) => {
    const y = top + i * rowH, open = phase === last;
    p.text(left, y + 16, `${phase.n}. ${clip(phase.title, 58)}`, { size: 13.5, weight: 700, fill: INK, halo: true });
    p.text(right, y + 16, phase.weekRange, { size: 12, fill: MUTED, anchor: 'end', halo: true });
    const xa = xOf(phase.weekStart), xb = Math.max(xa + 8, xOf(phase.weekEnd));
    p.rect(xa, y + 23, xb - xa, 14, { fill: '#e6efe6', stroke: GREEN, width: 1.6, dash: '5 3', radius: 3 });
    if (open) p.path(pathOf([[xb + 2, y + 23], [xb + 13, y + 30], [xb + 2, y + 37]], true), { fill: GREEN });
    else { p.path(pathOf([[xb, y + 21], [xb + 9, y + 30], [xb, y + 39], [xb - 9, y + 30]], true), { fill: INK, stroke: '#ffffff', width: 1.5 }); p.text(xb, y + 33.5, String.fromCharCode(64 + phase.n), { size: 9.5, weight: 700, fill: '#ffffff', anchor: 'middle' }); }
  });
  p.line(left, bottom + 4, right, bottom + 4, { stroke: MUTED, width: 1 });
  for (let w = 0; w <= maxWeek; w += step) p.text(xOf(w), bottom + 20, String(w), { size: 11.5, fill: MUTED, anchor: 'middle' });
  p.text((left + right) / 2, bottom + 38, t('weeks from the day work starts', 'amaviki kusukela ngosuku umsebenzi oqala ngalo'), { size: 12, fill: MUTED, anchor: 'middle' });
  const y = keyRow(p, left, bottom + 62, [
    { label: t('Hold point: stop and check before the next phase', 'Iphuzu lokuma: yima uhlole ngaphambi kwesigaba esilandelayo'), draw: (x, yy) => p.path(pathOf([[x + 10, yy - 8], [x + 18, yy], [x + 10, yy + 8], [x + 2, yy]], true), { fill: INK }) },
    { label: t('Carries on', 'Kuyaqhubeka'), draw: (x, yy) => p.path(pathOf([[x + 4, yy - 7], [x + 16, yy], [x + 4, yy + 7]], true), { fill: GREEN }) },
  ]);
  return {
    id: 'timeline', width: W, height: Math.ceil(y + 2), svg: p.done(y + 2),
    title: t('Order of work', 'Ukulandelana komsebenzi'),
    note: t('The order and rough length of each phase, worked out from what is on the saved design. The weeks are a planning guide, not a promise: weather, money and labour will move them. The order should not change.', 'Ukulandelana nobude obulinganiselwe besigaba ngasinye, kubalwe kulokho okusemklamweni ogciniwe. Amaviki ayisiqondiso sokuhlela, akusona isithembiso: isimo sezulu, imali nabasebenzi kuzowashintsha. Ukulandelana akufanele kushintshe.'),
    source: t('Build phases derived from the saved design', 'Izigaba zokwakha ezithathwe kumklamo ogciniwe'),
    alt: `${t('Order of work', 'Ukulandelana komsebenzi')}: ${phases.map(ph => `${ph.n}. ${ph.title} (${ph.weekRange})`).join('; ')}.`,
  };
}

// ── 7. How the ground is used ─────────────────────────────────────────────────────────────────

/** One bar = the whole measured site; the pieces are the areas the design and the map measure. */
export function landUseFigure(facts: ReportSiteFacts | null | undefined, language = 'en'): ReportFigure | null {
  const total = facts?.boundary?.areaM2;
  if (!finite(total) || total <= 0) return null;
  const t = translator(language);
  const p = pen();
  const raw = [
    { name: t('Vegetable beds', 'Imibhede yemifino'), value: facts?.design?.bedAreaM2, look: { fill: GREEN } as ShapeOptions },
    { name: t('Staple crop plots', 'Iziza zezitshalo eziyisisekelo'), value: facts?.design?.plotAreaM2, look: { fill: p.hatch('plot', AMBER, 5, 1.5), stroke: AMBER, width: 1.2 } as ShapeOptions },
    { name: t('Roof', 'Uphahla'), value: facts?.roof?.areaM2, look: { fill: SLATE } as ShapeOptions },
  ];
  const parts = raw.filter((part): part is typeof raw[number] & { value: number } => finite(part.value) && part.value > 0);
  const used = parts.reduce((sum, part) => sum + part.value, 0);
  // Pieces that add up to more than the site mean one of the measurements is wrong; draw nothing.
  if (!parts.length || used > total) return null;
  const rows = [...parts, { name: t('Everything else: paths, trees, yard, open ground', 'Konke okunye: izindlela, izihlahla, igceke, umhlaba ovulekile'), value: total - used, look: { fill: TRACK, stroke: HAIR, width: 1 } as ShapeOptions }];
  const x0 = 14, x1 = W - 14;
  p.text(x0, 24, `${t('The whole site', 'Indawo yonke')}: ${figureNumber(total)} m²`, { size: 16, weight: 700, fill: INK });
  let x = x0;
  for (const part of rows) { const w = (part.value / total) * (x1 - x0); p.rect(x + 1, 38, Math.max(1.5, w - 2), 30, { ...part.look, radius: 3 }); x += w; }
  let y = 96;
  for (const part of rows) {
    p.rect(x0, y - 11, 18, 13, { ...part.look, radius: 2 });
    p.text(x0 + 28, y, part.name, { size: 13 });
    const share = (part.value / total) * 100;
    p.text(x1, y, `${figureNumber(part.value)} m²   ${share < 1 ? '<1' : figureNumber(share)} %`, { size: 13, weight: 700, fill: INK, anchor: 'end' });
    y += 23;
  }
  return {
    id: 'land-use', width: W, height: Math.ceil(y), svg: p.done(y),
    title: t('How the ground is used', 'Ukuthi umhlaba usetshenziswa kanjani'),
    note: t('Areas as drawn on the saved design and traced on the map, whether built yet or not. Trees, paths and tanks are not counted as areas.', 'Izindawo njengoba zidwetshwe kumklamo ogciniwe nakumephu, noma sezakhiwe noma cha. Izihlahla, izindlela namathangi akubalwa njengezindawo.'),
    source: `${t('Boundary', 'Umngcele')}: ${facts?.boundary?.source ?? t('traced on the map', 'udwetshwe kumephu')}. ${t('Beds and plots: saved design.', 'Imibhede neziza: umklamo ogciniwe.')}`,
    alt: `${t('Land use', 'Ukusetshenziswa komhlaba')}: ${rows.map(part => `${part.name} ${figureNumber(part.value)} m²`).join('; ')}.`,
  };
}

// ── 8. Built and still to build ───────────────────────────────────────────────────────────────

/** One mark per thing on the design: filled = already there, ring = planned. Repeated, never scaled. */
export function statusFigure(canvas: DesignCanvasState | null | undefined, language = 'en'): ReportFigure | null {
  if (!canvas) return null;
  const t = translator(language);
  const names: Record<PlanPaint | 'plot' | 'route', string> = {
    bed: t('Vegetable beds', 'Imibhede yemifino'), plot: t('Staple crop plots', 'Iziza zezitshalo eziyisisekelo'), planting: t('Trees and plants', 'Izihlahla nezitshalo'), water: t('Water', 'Amanzi'),
    structure: t('Structures', 'Izakhiwo'), earthworks: t('Earthworks', 'Imisebenzi yomhlaba'), animal: t('Animals', 'Izilwane'), access: t('Access', 'Ukufinyelela'), route: t('Paths, swales and pipes', 'Izindlela, imisele namapayipi'),
  };
  const order: Array<keyof typeof names> = ['bed', 'plot', 'planting', 'water', 'earthworks', 'structure', 'animal', 'access', 'route'];
  const tally = new Map<keyof typeof names, { built: number; planned: number }>();
  const add = (key: keyof typeof names, planned: boolean) => { const row = tally.get(key) ?? { built: 0, planned: 0 }; if (planned) row.planned += 1; else row.built += 1; tally.set(key, row); };
  for (const item of canvas.items ?? []) { const def = ELEMENTS_BY_ID[item.defId]; if (def) add((BED_DEF_IDS as readonly string[]).includes(item.defId) ? 'bed' : CATEGORY_PAINT[def.category], statusOf(item) === 'proposed'); }
  for (const zone of canvas.zones ?? []) if (zone.feature === 'staple_garden') add('plot', statusOf(zone) === 'proposed');
  for (const line of canvas.lines ?? []) add('route', statusOf(line) === 'proposed');
  const rows = order.filter(key => tally.has(key)).map(key => ({ key, ...tally.get(key)! }));
  if (!rows.length) return null;
  const p = pen();
  const built = rows.reduce((sum, row) => sum + row.built, 0), planned = rows.reduce((sum, row) => sum + row.planned, 0);
  p.text(14, 25, `${figureNumber(built)} ${t('already there', 'sekukhona')}  ·  ${figureNumber(planned)} ${t('still to build or plant', 'kusazokwakhiwa noma kutshalwe')}`, { size: 17, weight: 700, fill: INK });
  const dotsX = 196, pitch = 17, perRow = Math.floor((W - 14 - 96 - dotsX) / pitch);
  let y = 56;
  for (const row of rows) {
    p.text(14, y + 4, names[row.key], { size: 13 });
    const count = row.built + row.planned, shown = Math.min(count, perRow - 2);
    for (let i = 0; i < shown; i++) { const x = dotsX + i * pitch; if (i < row.built) p.circle(x, y, 6, { fill: GREEN }); else p.circle(x, y, 5.2, { fill: '#ffffff', stroke: GREEN, width: 1.8, dash: '3 2' }); }
    if (count > shown) p.text(dotsX + shown * pitch, y + 4, `+${count - shown}`, { size: 12, fill: MUTED });
    p.text(W - 14, y + 4, `${row.built} / ${count}`, { size: 13, weight: 700, fill: INK, anchor: 'end' });
    y += 25;
  }
  y = keyRow(p, 14, y + 8, [
    { label: t('Already there', 'Sekukhona'), draw: (x, yy) => p.circle(x + 10, yy, 6, { fill: GREEN }) },
    { label: t('Planned, not built or planted yet', 'Kuhleliwe, akukakhiwa noma kutshalwe'), draw: (x, yy) => p.circle(x + 10, yy, 5.2, { fill: '#ffffff', stroke: GREEN, width: 1.8, dash: '3 2' }) },
    { label: t('Numbers: there now / total', 'Izinombolo: okukhona manje / isamba'), draw: () => undefined },
  ]);
  return {
    id: 'status', width: W, height: Math.ceil(y), svg: p.done(y),
    title: t('Built, and still to build', 'Okwakhiwe, nokusazokwakhiwa'),
    note: t('One mark for each thing on the saved design, as it was marked there. Change an item to "existing" in the Design Studio once it is in the ground.', 'Uphawu olulodwa lwento ngayinye esemklamweni ogciniwe, njengoba yaphawulwa khona. Shintsha into ibe "ekhona" ku-Design Studio uma isisemhlabathini.'),
    source: `${t('Saved design', 'Umklamo ogciniwe')}${typeof canvas.updatedAt === 'string' ? ` (${canvas.updatedAt.slice(0, 10)})` : ''}`,
    alt: `${t('Built and planned', 'Okwakhiwe nokuhleliwe')}: ${rows.map(row => `${names[row.key]} ${row.built}/${row.built + row.planned}`).join('; ')}.`,
  };
}

// Every month axis runs Jan→Dec. A Jul→Jun "water year" was considered and declined: it suits a
// summer-rainfall site and splits the wet season of a winter-rainfall one, and the crop calendar,
// the tank calculator and the farmer's own diary all read Jan→Dec. The seasons are named instead.
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const twelve = (values: unknown): values is number[] => Array.isArray(values) && values.length === 12 && values.every(finite);

/** A zero-based axis with round steps (1, 2 or 5 × 10ⁿ) and about `target` divisions. */
function axis(max: number, target = 4) {
  const raw = Math.max(max, 1e-9) / target;
  const pow = 10 ** Math.floor(Math.log10(raw));
  const step = ([1, 2, 5, 10].find(m => m * pow >= raw - 1e-12) ?? 10) * pow;
  const top = Math.max(step, Math.ceil(max / step - 1e-9) * step);
  const ticks: number[] = [];
  for (let v = 0; v <= top + step / 2; v += step) ticks.push(v);
  return { top, ticks };
}

/** "Oct–Mar" → [9,10,11,0,1,2]. Anything it cannot read gives [] and that season is not drawn. */
function seasonMonths(label: string | undefined): number[] {
  const m = /^\s*([A-Za-z]{3})[a-z]*\s*[–—-]\s*([A-Za-z]{3})[a-z]*\s*$/.exec(label ?? '');
  if (!m) return [];
  const at = (s: string) => MONTHS.findIndex(x => x.toLowerCase() === s.toLowerCase());
  const from = at(m[1]), to = at(m[2]);
  if (from < 0 || to < 0) return [];
  const out: number[] = [];
  for (let i = from; out.length < 12; i = (i + 1) % 12) { out.push(i); if (i === to) break; }
  return out;
}

/** Flagged months as readable runs, joining a run that wraps the year end: "Nov–Feb, Jun". */
function monthRuns(flags: boolean[]): string {
  if (!flags.some(Boolean)) return '';
  if (flags.every(Boolean)) return 'Jan–Dec';
  const runs: string[] = [];
  const start = flags.indexOf(false);
  let open = -1;
  for (let k = 1; k <= 12; k++) {
    const i = (start + k) % 12;
    if (flags[i]) { if (open < 0) open = i; continue; }
    if (open >= 0) { const end = (i + 11) % 12; runs.push(open === end ? MONTHS[open] : `${MONTHS[open]}–${MONTHS[end]}`); open = -1; }
  }
  return runs.join(', ');
}

/** A bar standing on the baseline: soft at the data end, square where it meets the axis. */
function barPath(x: number, base: number, w: number, h: number, r = 4) {
  if (!(h > 0)) return '';
  const rr = Math.min(r, h, w / 2), y = base - h;
  return `M${px(x)} ${px(base)}V${px(y + rr)}Q${px(x)} ${px(y)} ${px(x + rr)} ${px(y)}H${px(x + w - rr)}Q${px(x + w)} ${px(y)} ${px(x + w)} ${px(y + rr)}V${px(base)}Z`;
}

const monthLabels = (p: Pen, left: number, slot: number, y: number) => MONTHS.forEach((m, i) => p.text(left + slot * (i + 0.5), y, m, { size: 12, fill: MUTED, anchor: 'middle' }));

type KeyEntry = { draw: (x: number, y: number) => void; label: string };
/** Key entries left to right, wrapping to the drawing's width. Returns the y under the last row. */
function keyRow(p: Pen, x0: number, y: number, entries: KeyEntry[], maxX = W - 14): number {
  let x = x0;
  for (const entry of entries) {
    const w = 28 + textWidth(entry.label, 12) + 16;
    if (x > x0 && x + w > maxX) { x = x0; y += 21; }
    entry.draw(x, y);
    p.text(x + 28, y + 4, entry.label, { size: 12 });
    x += w;
  }
  return y + 21;
}

/** Wrapped sentence block. Returns the y under the last line. */
function paragraph(p: Pen, x: number, y: number, value: string, width: number, o: TextOptions = {}): number {
  const size = o.size ?? 13;
  for (const line of wrapText(value, size, width)) { p.text(x, y, line, { ...o, size }); y += Math.round(size * 1.42); }
  return y;
}


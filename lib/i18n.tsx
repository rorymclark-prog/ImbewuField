// Locale dictionaries that have finished loading. English is present from module init; every
// other code lands here asynchronously the first time it is needed (see loadLocale).
const LOADED: Record<string, Dict> = { en: T_en };

// Fetches and caches a locale's dictionary. Safe to call repeatedly — a second call while the
// first is still in flight, or after the locale has already landed, is a no-op beyond the
// (idempotent) dynamic import. Exported so the language-pick screen can prefetch every locale up
// front (see components/Onboarding.tsx) instead of waiting for each pick one at a time.
export async function loadLocale(code: string): Promise<void> {
  if (LOADED[code]) return;
  const mod = (await import(`./locales/${code}`)) as { default: Dict };
  LOADED[code] = mod.default;
}

// Look up a string in any language (used by onboarding to preview before committing). Reads
// whatever has already loaded, synchronously — a locale whose chunk has not landed yet falls back
// to English for that call; once loadLocale() resolves, the next call sees the real text.
export function translate(lang: string, key: string): string {
  return LOADED[lang]?.[key] ?? LOADED.en[key] ?? key;
}

interface LangCtx {
  lang: string;
  setLang: (code: string) => void;
  t: (key: string) => string;
  onboarded: boolean;
  completeOnboarding: (code: string) => void;
}

const Ctx = createContext<LangCtx>({
  lang: 'en', setLang: () => {}, t: (k) => k, onboarded: true, completeOnboarding: () => {},
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState('en');
  const [onboarded, setOnboarded] = useState(true); // assume true until we check, avoids modal flash on SSR
  const [, setLoadTick] = useState(0); // bumped once a lazily-loaded locale lands, so t() re-renders

  useEffect(() => {
    const saved = localStorage.getItem('permamap_lang');
    const done = localStorage.getItem(activeAccountLocalStorageKey(ONBOARD_KEY)) === '1';
    if (saved) setLangState(saved);
    setOnboarded(done);

    // Keep any deliberately nested preview/example provider in step with the root provider
    // during same-tab language changes.
    return listenForLanguageChanges(window, setLangState);
  }, []);

  // Fetches the active locale's chunk whenever `lang` changes — covering the initial mount
  // (English, already loaded, so this is a no-op), setLang, and the cross-tab listener above —
  // then bumps loadTick so t() re-renders once the real dictionary has landed. Until then, t()
  // already falls back to English via LOADED[lang] ?? LOADED.en, so the UI never renders raw keys.
  useEffect(() => {
    let cancelled = false;
    loadLocale(lang).then(() => {
      if (!cancelled) setLoadTick((n) => n + 1);
    });
    return () => {
      cancelled = true;
    };
  }, [lang]);

  const setLang = (code: string) => {
    setLangState(code);
    localStorage.setItem('permamap_lang', code);
    announceLanguageChange(window, code);
  };
  const completeOnboarding = (code: string) => {
    setLang(code);
    localStorage.setItem(activeAccountLocalStorageKey(ONBOARD_KEY), '1');
    removeSignedInLegacyLocalStorageKey(ONBOARD_KEY);
    setOnboarded(true);
  };
  const t = (key: string) => LOADED[lang]?.[key] ?? LOADED.en[key] ?? key;

  return <Ctx.Provider value={{ lang, setLang, t, onboarded, completeOnboarding }}>{children}</Ctx.Provider>;
}

export const useLanguage = () => useContext(Ctx);

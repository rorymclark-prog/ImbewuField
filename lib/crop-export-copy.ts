import { cropByKey } from './crop-catalog';
import type { PoultryGuidance } from './animal-enterprises';
import { CROP_EXPORT_COPY } from './crop-export-copy-data';
import { recordsMonthShort } from './records-months';
import type { PreservedFoodMethod } from './production-records';

export const CROP_EXPORT_DRAFT_LANGUAGES = ['zu', 'st', 'ts', 've'] as const;
export type CropExportDraftLanguage = typeof CROP_EXPORT_DRAFT_LANGUAGES[number];
export const isCropExportDraftLanguage = (language: string): language is CropExportDraftLanguage =>
  CROP_EXPORT_DRAFT_LANGUAGES.some(code => code === language);

// Check all four required languages once; presenters need strings, not a union of every long draft.
type CropExportCopyRow = Readonly<{ english: string; zu: string; st: string; ts: string; ve: string; generatedScope?: string }>;
const copyRows: readonly CropExportCopyRow[] = CROP_EXPORT_COPY;
const exportCopy = new Map<string, CropExportCopyRow>(copyRows.map(row => [row.english, row]));

/** Values are recorded data. Interpolate once so a bed named {count} stays that bed. */
export function cropExportText(source: string, language = 'en', values: Record<string, string | number> = {}): string {
  const row = exportCopy.get(source);
  const wording = row && isCropExportDraftLanguage(language) ? row[language] : source;
  return wording.replace(/\{(\w+)\}/g, (token, key: string) => Object.hasOwn(values, key) ? String(values[key]) : token);
}

const preservedMethodSources: Record<PreservedFoodMethod, string> = { stored: 'Stored', frozen: 'Frozen', dried: 'Dried', fermented: 'Fermented', processed: 'Processed' };
export function cropPreservedMethodText(method: PreservedFoodMethod, language = 'en'): string {
  if (!Object.hasOwn(preservedMethodSources, method)) return method;
  return isCropExportDraftLanguage(language) ? cropExportText(preservedMethodSources[method], language) : method;
}

/** Only generated projection periods enter here; private record dates/names are never reparsed. */
export function cropProjectionPeriodText(source: string, language = 'en'): string {
  if (!isCropExportDraftLanguage(language)) return source;
  const period = /^([A-Za-z]+) (\d{4}) ([–-]) ([A-Za-z]+) (\d{4})$/.exec(source);
  if (!period) return source;
  const months = Array.from({ length: 12 }, (_, index) => new Date(2000, index, 1).toLocaleDateString('en-ZA', { month: 'short' }));
  const first = months.indexOf(period[1]), last = months.indexOf(period[4]);
  if (first < 0 || last < 0) return source;
  return `${recordsMonthShort(language, first + 1)} ${period[2]} ${period[3]} ${recordsMonthShort(language, last + 1)} ${period[5]}`;
}

const escapeSourcePattern = (source: string) => source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const generatedIssuePatterns = copyRows.filter(row => 'generatedScope' in row && row.generatedScope === 'production-issue').map(row => {
  const keys: string[] = [];
  const parts = row.english.split(/(\{\w+\})/g).map(part => {
    if (!/^\{\w+\}$/.test(part)) return escapeSourcePattern(part);
    const key = part.slice(1, -1); keys.push(key);
    return key === 'date' ? '(\\d{1,4}-\\d{2})' : '(.+?)';
  });
  return { source: row.english, keys, pattern: new RegExp('^' + parts.join('') + '$') };
});

/** Match the producer's complete source sentence, then interpolate recorded values exactly once. */
export function cropProductionIssueText(source: string, language = 'en'): string {
  if (!isCropExportDraftLanguage(language)) return source;
  for (const row of generatedIssuePatterns) {
    const match = row.pattern.exec(source);
    if (!match) continue;
    const values = Object.fromEntries(row.keys.map((key, index) => [key, match[index + 1]]));
    if (values.period) values.period = cropProjectionPeriodText(values.period, language);
    if (values.unit && ['eggs', 'litres', 'items'].includes(values.unit)) values.unit = cropExportText({ eggs: 'Eggs', litres: 'Litres', items: 'Items' }[values.unit]!, language).toLowerCase();
    return cropExportText(row.source, language, values);
  }
  return cropExportText('Original message: {message}', language, { message: source });
}

const projectionDetails = new Map<string, CropExportCopyRow>(copyRows.filter(row => 'generatedScope' in row && row.generatedScope === 'projection-detail').map(row => [row.english, row]));
/** Only the projection producer's complete generated messages are translated here. */
export function cropProjectionDetailText(source: string, language = 'en'): string {
  if (!isCropExportDraftLanguage(language)) return source;
  if (projectionDetails.has(source)) return cropExportText(source, language);
  const count = /^(\d+(?:\.\d+)?(?:e[+-]?\d+)?) plants need age groups$/.exec(source);
  if (count) return cropExportText('{count} plants need age groups', language, { count: count[1] });
  return cropExportText('Original message: {message}', language, { message: source });
}

/** Age ranges are generated by the unchanged age model, never parsed from farmer notes. */
export function cropProjectionAgeText(source: string, language = 'en'): string {
  if (!isCropExportDraftLanguage(language)) return source;
  return source.split('; ').map(age => {
    if (age === '?') return age;
    if (age === 'not planted' || age === 'Age not recorded') return cropExportText(age, language);
    const range = /^(\d+\.\d+)–(\d+\.\d+) yr$/.exec(age);
    return range ? cropExportText('{from}–{to} yr', language, { from: range[1], to: range[2] })
      : cropExportText('Original message: {message}', language, { message: age });
  }).join('; ');
}

const poultrySources = new Set<string>(copyRows.filter(row => 'generatedScope' in row && row.generatedScope === 'poultry-guidance').map(row => row.english));
/** Translate authored care fields only; a recorded breed matching a source word stays recorded. */
export function cropPoultryGuidance(source: PoultryGuidance, language = 'en'): PoultryGuidance {
  if (!isCropExportDraftLanguage(language)) return source;
  const authored = (text: string) => poultrySources.has(text) ? cropExportText(text, language)
    : cropExportText('Original source note: {note}', language, { note: text });
  return {
    ...source,
    statusText: authored(source.statusText), missing: source.missing.map(authored), attention: source.attention.map(authored),
    careNotes: source.careNotes.map(point => ({ ...point, text: authored(point.text) })),
    climateNotes: source.climateNotes.map(point => ({ ...point, text: authored(point.text) })),
    options: source.options.map(option => ({ ...option, name: option.kind === 'management-system' ? authored(option.name) : option.name, detail: authored(option.detail) })),
    localCheck: authored(source.localCheck),
  };
}

const planNoteSources = new Set<string>(copyRows.filter(row => (row.generatedScope === 'plan-note' || row.generatedScope === 'plan-note-authored')).map(row => row.english));
const planNoteFrames = new Map<string, string>(copyRows.filter(row => row.generatedScope?.startsWith('plan-note-') && row.generatedScope !== 'plan-note-calendar').map(row => [row.generatedScope!, row.english]));
const planNoteCalendars = copyRows.filter(row => row.generatedScope === 'plan-note-calendar').map(row => row.english);
type SavedPlanNoteContext = Readonly<{ unplacedCropKeys?: readonly string[]; bedIds?: readonly string[] }>;

/** Saved reasons describe the accepted snapshot; never rebuild them from today's edited plan. */
export function cropPlanNoteText(source: string, language = 'en', context?: SavedPlanNoteContext): string {
  if (!isCropExportDraftLanguage(language)) return source;
  if (planNoteSources.has(source)) return cropExportText(source, language);
  const rest = planNoteFrames.get('plan-note-rest-year-one'), reason = planNoteFrames.get('plan-note-plot-rest-reason');
  if (rest && reason && Array.isArray(context?.bedIds) && context.bedIds.length === 1) {
    const prefix = '1 growing area has a stretch with no new sowing: ', suffix = ' (all year). ' + reason;
    if (source.startsWith(prefix) && source.endsWith(suffix)) {
      const place = source.slice(prefix.length, -suffix.length);
      if (source === cropExportText(rest, 'en', { count: '1', place, period: 'all year', reason })) {
        return cropExportText(rest, language, { count: '1', place, period: cropExportText('All year', language).toLowerCase(), reason: cropExportText(reason, language) });
      }
    }
  }
  const keys = context?.unplacedCropKeys;
  if (Array.isArray(keys) && keys.length) {
    const crops = keys.map(key => typeof key === 'string' ? cropByKey(key) : undefined);
    if (crops.every(crop => crop !== undefined)) {
      const names = crops.map(crop => crop.name).join(', '), count = crops.length === 1 ? 'one' : 'many';
      const window = planNoteFrames.get('plan-note-window-' + count);
      if (window) for (const calendar of planNoteCalendars) {
        if (source === cropExportText(window, 'en', { crops: names, calendar })) {
          return cropExportText(window, language, { crops: names, calendar: cropExportText(calendar, language) });
        }
      }
      const unplaced = planNoteFrames.get('plan-note-unplaced-' + count);
      if (unplaced) {
        const head = cropExportText(unplaced, 'en', { crops: names });
        if (source === head) return cropExportText(unplaced, language, { crops: names });
        if (source.startsWith(head)) {
          // This count and rounded area belong to the saved suggestion, even after the map changes.
          const tail = /^ This plan had ([1-9]\d*) veg bed(s?) \((0|[1-9]\d*) m² in all\) — add beds on the map to fit more of your choices\.$/.exec(source.slice(head.length));
          if (tail && tail[2] === (tail[1] === '1' ? '' : 's')) {
            const space = planNoteFrames.get('plan-note-space-' + (tail[1] === '1' ? 'one' : 'many'));
            if (space) return cropExportText(unplaced, language, { crops: names }) + cropExportText(space, language, { beds: tail[1], area: tail[3] });
          }
        }
      }
    }
  }
  return cropExportText('Original saved plan note: {note}', language, { note: source });
}

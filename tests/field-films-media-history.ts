export const fieldFilmMedia = new Map(media.map(([name, bytes, sha256]) => [folder + name, { bytes, sha256 }]));
const manifestDigest = 'dba9ce8f2ad53af0f4ea3e59496ba5b4f30c285159fba246b26e6371a964227a';

export function fieldFilmSizesBefore<T extends string | Uint8Array>(file: string, supplied: T, requirePublished = false): T {
  if (file !== 'lib/course-asset-sizes.ts') return supplied;
  const digest = createHash('sha256').update(supplied).digest('hex');
  if (requirePublished) assert.equal(digest, manifestDigest, 'the published catalogue includes the complete field-film release');
  if (digest !== manifestDigest) return supplied;
  const removed = new Set<string>();
  const text = typeof supplied === 'string' ? supplied : Buffer.from(supplied).toString('utf8');
  const before = text.replace(/^  '([^']+)': (\d+),\n/gm, (line, url: string, bytes: string) => {
    const asset = fieldFilmMedia.get('public' + url);
    if (!asset) return line;
    assert.equal(Number(bytes), asset.bytes, url + ': generated byte count for the field edition');
    removed.add(url);
    return '';
  }).replace('// 1961 files, 687.6 MB total.', '// 1941 files, 653.0 MB total.');
  assert.equal(removed.size, fieldFilmMedia.size, 'the size manifest accounts for all eight movies and twelve captions');
  return (typeof supplied === 'string' ? before : Buffer.from(before)) as T;
}

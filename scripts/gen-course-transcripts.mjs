#!/usr/bin/env node
// Picture-led teaching still needs the full authored words when a learner cannot hear the voice.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { COURSE_NARRATION } from '../lib/course-audio.ts';
import { parseScriptBlocks } from '../lib/narration-check.ts';

export function collectTranscripts() {
  const result = {};
  for (const [moduleId, narration] of Object.entries(COURSE_NARRATION)) {
    result[moduleId] = {};
    // The audio manifest is the release boundary. Draft translations must not leak into the UI.
    for (const lang of narration.languages) {
      const source = readFileSync(new URL(`../docs/narration/${moduleId}.${lang}.md`, import.meta.url), 'utf8');
      const blocks = parseScriptBlocks(source);
      const registered = narration.tracks.map(t => t.slide);
      if (JSON.stringify(blocks.map(b => b.slide)) !== JSON.stringify(registered)) {
        throw new Error(`${moduleId}/${lang}: script and published narration differ`);
      }
      result[moduleId][lang] = Object.fromEntries(blocks.map(block => [block.slide,
        block.text.replace(/\[pause\]/gi, '').replace(/^---\s*$/gm, '')
          .split(/\n\s*\n/).map(p => p.trim()).filter(Boolean),
      ]));
    }
  }
  return result;
}

if (fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = '// GENERATED by scripts/gen-course-transcripts.mjs from published narration languages.\n'
    + '// Bundled with the player so reading a downloaded lesson needs no extra network request.\n'
    + 'export const COURSE_TRANSCRIPTS: Readonly<Record<string, Record<string, Record<number, string[]>>>> = '
    + JSON.stringify(collectTranscripts(), null, 2) + ';\n';
  writeFileSync(new URL('../lib/course-transcripts.ts', import.meta.url), text);
  console.log(`Generated published transcripts (${Buffer.byteLength(text)} bytes)`);
}

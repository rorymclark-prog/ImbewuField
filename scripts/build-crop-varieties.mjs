#!/usr/bin/env node
// research/crop-sources/varieties/*.json  →  lib/crop-varieties-data.ts
//
// The dossiers are the record: each cultivar with the growing zones its source named it for,
// the verbatim sentence, URL and page, plus the researcher's notes and gaps. This keeps only
// what the app shows — the cultivar, its zones and season, and its citations.
//
// Dropped on the way:
//   - evidence that is not an outside document (the "Existing ImbewuField lib/crop-catalog.ts"
//     lines and internal: URLs — the app citing itself is not a source);
//   - any cultivar or zone note left with no outside source after that. The catalog's own
//     generic advice ("Short-day type", "Accord F1 (or similar ...)") still shows from
//     lib/crop-catalog.ts's `varieties`, labelled as general guidance.
//
// Run:
//   node scripts/build-crop-varieties.mjs
// tests/crop-varieties.test.ts fails if the generated file and the dossiers disagree.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'research/crop-sources/varieties');
const out = join(root, 'lib/crop-varieties-data.ts');

export const isOutsideSource = (ev) =>
  !!ev && typeof ev.quote === 'string' && ev.quote.trim() !== ''
  && !(ev.url || '').startsWith('internal:')
  && !/ImbewuField/.test(ev.doc || '');

// The dossier's doc names carry the researcher's process notes — "(fetched directly, verbatim)",
// "(via search snippet — JS-rendered page ...)". Those stay in the dossier; the farmer sees the
// document's name.
const PROCESS_NOTE = /fetched|verbatim|snippet|mirror|JS-rendered|read in full|this (session|pass|attempt)/i;
export const docLabel = (doc) =>
  (doc || '').replace(/\s*\(([^()]*)\)/g, (m, inner) => (PROCESS_NOTE.test(inner) ? '' : m)).trim();

const cite = (ev) => ({ quote: ev.quote, url: ev.url || null, doc: docLabel(ev.doc), page: ev.page ?? null });

const sourcesOf = (evidence) => (evidence || []).filter(isOutsideSource).map(cite);

export function varietiesFromDossier(d) {
  const varieties = (d.varieties || [])
    .map((v) => ({
      name: v.name,
      zones: v.zones || [],
      season: v.season || null,
      maturity: v.maturity || null,
      traits: v.traits || null,
      type: v.type === 'OP' || v.type === 'hybrid' ? v.type : null,
      sources: sourcesOf(v.evidence),
    }))
    .filter((v) => v.sources.length > 0);
  const zoneAdvice = {};
  for (const [zone, a] of Object.entries(d.zoneAdvice || {})) {
    const sources = sourcesOf(a && a.evidence);
    if (a && a.text && sources.length > 0) zoneAdvice[zone] = { text: a.text, sources };
  }
  return { varieties, zoneAdvice };
}

export function loadDossiers() {
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => ({ key: f.replace(/\.json$/, ''), ...JSON.parse(readFileSync(join(dir, f), 'utf8')) }));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = {};
  for (const d of loadDossiers()) {
    const rec = varietiesFromDossier(d);
    if (rec.varieties.length > 0 || Object.keys(rec.zoneAdvice).length > 0) data[d.key] = rec;
  }
  writeFileSync(out, [
    '// GENERATED by scripts/build-crop-varieties.mjs from research/crop-sources/varieties/*.json.',
    '// Do not edit by hand: correct the dossier and re-run the script. See lib/crop-varieties.ts.',
    '',
    "import type { CropVarietyRecord } from './crop-varieties';",
    '',
    `export const CROP_VARIETY_DATA: Record<string, CropVarietyRecord> = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n'));
  console.log(`wrote ${Object.keys(data).length} crops to ${out}`);
}

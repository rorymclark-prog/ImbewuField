#!/usr/bin/env node
// Builds lib/records-regional-drafts-data.ts from the reviewed drafting packets in
// docs/translation-reviews/records-finance-2026-10-06/ (inventory.json + draft-<lang>.json).
// The data file is generated so the packet stays the one place the review status and notes live;
// a hold never reaches the data file, so the screen shows its exact English.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DIR = join(ROOT, 'docs/translation-reviews/records-finance-2026-10-06');
const inventory = JSON.parse(readFileSync(join(DIR, 'inventory.json'), 'utf8'));
const placeholders = (s) => [...s.matchAll(/\{([a-zA-Z]+)\}/g)].map((m) => m[1]).sort().join(',');
const rows = {};
const problems = [];
for (const lang of ['zu', 'st', 've', 'ts']) {
  let drafts;
  try { drafts = JSON.parse(readFileSync(join(DIR, `draft-${lang}.json`), 'utf8')); } catch { continue; }
  for (const d of drafts) {
    const item = inventory.find((i) => i.id === d.id);
    if (!item || item.english !== d.english) { problems.push(`${lang} ${d.id}: english does not match inventory`); continue; }
    if (d.status !== 'accepted') continue; // only root-accepted drafts ship
    if (placeholders(d.english) !== placeholders(d.draft)) { problems.push(`${lang} ${d.id}: placeholder drift`); continue; }
    (rows[d.english] ??= {})[lang] = d.draft;
  }
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const body = Object.keys(rows).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(rows[k])},`).join('\n');
writeFileSync(join(ROOT, 'lib/records-regional-drafts-data.ts'), `// GENERATED by scripts/build-records-drafts.mjs from docs/translation-reviews/records-finance-2026-10-06/.
// Do not edit by hand: change the packet's draft-<lang>.json and rebuild. Keyed by exact English
// (see lib/records-regional-drafts.ts). Unreviewed machine drafts — Rory authorised these for later
// facilitator review on 6 October 2026; none has been checked by a fluent speaker or local farming reviewer.
export type RecordsDraftRow = { zu?: string; st?: string; ve?: string; ts?: string };

export const RECORDS_DRAFTS: Record<string, RecordsDraftRow> = {
${body}
};
`);
console.log(`wrote ${Object.keys(rows).length} English keys`);

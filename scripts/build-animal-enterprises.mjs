#!/usr/bin/env node
// research/animal-sources/*.json  →  lib/animal-enterprises-data.ts
//
// The same arrangement as the orchard table (scripts/build-perennial-harvest.mjs): the dossiers
// are the record — each value with the verbatim sentence, URL and page it came from, plus the
// researcher's notes and gaps — and this keeps only what the app shows.
//
// A dossier value that failed quote verification is set to null IN THE DOSSIER (with a gaps line
// saying why) before this runs; this script does no judging of its own. Run:
//   node scripts/build-animal-enterprises.mjs
// tests/animal-enterprises.test.ts fails if the generated file and the dossiers disagree.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'research/animal-sources');
const out = join(root, 'lib/animal-enterprises-data.ts');

const cite = (ev) => ev && ({ quote: ev.quote, url: ev.url, doc: ev.doc, page: ev.page ?? null });

const range = (field) => {
  if (!field || !Array.isArray(field.value) || !field.evidence) return null;
  const r = { value: [field.value[0], field.value[1]], source: cite(field.evidence) };
  if (field.notes) r.note = field.notes;
  return r;
};

const points = (list) => (list || [])
  .filter((p) => p && p.point && p.evidence)
  .map((p) => ({ point: p.point, source: cite(p.evidence) }));

export function enterpriseFromDossier(d) {
  return {
    enterpriseId: d.enterpriseId,
    name: d.commonName,
    animal: d.animal,
    animalUnit: d.animalUnit,
    product: d.product,
    outputUnit: d.outputUnit,
    outputPerAnimal: range(d.outputPerAnimal),
    windows: (d.productionMonths || [])
      .filter((w) => Array.isArray(w.months) && w.months.length > 0 && w.evidence)
      .map((w) => ({ region: w.region, months: w.months, source: cite(w.evidence) })),
    seasonalPattern: d.seasonalPattern && d.seasonalPattern.value && d.seasonalPattern.evidence
      ? { text: d.seasonalPattern.value, source: cite(d.seasonalPattern.evidence) }
      : null,
    // Honey only, so far: one plant's flow in one place, never charted as months — see
    // CalendarHoneyLine in lib/calendar-produce.ts and the round-4 line in bees.json's gaps.
    flowNote: d.flowNote && d.flowNote.value && d.flowNote.evidence
      ? { text: d.flowNote.value, source: cite(d.flowNote.evidence) }
      : null,
    flowRecords: (d.flowRecords || [])
      .filter((r) => r && r.region && r.when && r.evidence)
      .map((r) => ({ region: r.region, when: r.when, plant: r.plant ?? null, source: cite(r.evidence) })),
    weeksToFirstProduct: range(d.timeToFirstProductWeeks),
    productiveLifeYears: range(d.productiveLifeYears),
    feedKgPerDay: range(d.feedKgPerAnimalPerDay),
    waterLPerDay: range(d.waterLPerAnimalPerDay),
    spaceM2: range(d.spaceM2PerAnimal),
    welfare: points(d.welfare),
    legal: points(d.legal),
  };
}

export function loadDossiers() {
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = Object.fromEntries(loadDossiers().map((d) => [d.enterpriseId, enterpriseFromDossier(d)]));
  writeFileSync(out, [
    '// GENERATED by scripts/build-animal-enterprises.mjs from research/animal-sources/*.json.',
    '// Do not edit by hand: correct the dossier and re-run the script. See lib/animal-enterprises.ts.',
    '',
    "import type { AnimalEnterprise } from './animal-enterprises';",
    '',
    `export const ANIMAL_ENTERPRISE_DATA: Record<string, AnimalEnterprise> = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n'));
  console.log(`wrote ${Object.keys(data).length} enterprises to ${out}`);
}

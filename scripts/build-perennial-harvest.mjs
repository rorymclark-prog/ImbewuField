#!/usr/bin/env node
// research/perennial-sources/*.json  →  lib/perennial-harvest-data.ts
//
// The dossiers are the record: each value with the verbatim sentence, URL and page it came from,
// plus the notes and gaps the researcher left. This keeps only what the app shows — values and
// their citations — so the notes and search logs are not shipped to every phone.
//
// A dossier value that failed quote verification is set to null IN THE DOSSIER (with a gaps line
// saying why) before this runs; this script does no judging of its own. Run:
//   node scripts/build-perennial-harvest.mjs
// tests/perennial-harvest.test.ts fails if the generated file and the dossiers disagree.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'research/perennial-sources');
const out = join(root, 'lib/perennial-harvest-data.ts');

/** The catalogue's leading common name, as lib/perennial-produce.ts's produceLabel reads it. */
const produceLabel = (commonName) => commonName.split('/')[0].replace(/\([^)]*\)/g, '').replace(/\s+/g, ' ').trim();

const cite = (ev) => ev && ({ quote: ev.quote, url: ev.url, doc: ev.doc, page: ev.page ?? null });

const range = (field) => {
  if (!field || !Array.isArray(field.value) || !field.evidence) return null;
  const r = { value: [field.value[0], field.value[1]], source: cite(field.evidence) };
  if (field.notes) r.note = field.notes;
  return r;
};

export function harvestFromDossier(d) {
  return {
    speciesId: d.speciesId,
    name: produceLabel(d.commonName),
    product: d.harvestProduct || 'fruit',
    windows: (d.harvestMonths || [])
      .filter((w) => Array.isArray(w.months) && w.months.length > 0 && w.evidence)
      .map((w) => ({ region: w.region, months: w.months, source: cite(w.evidence) })),
    yearsToFirstCrop: range(d.yearsToFirstCrop),
    yearsToFullBearing: range(d.yearsToFullBearing),
    yieldKgPerTree: range(d.yieldKgPerTreeMature),
    chillUnits: range(d.chillUnits),
    pollination: d.pollination && d.pollination.value && d.pollination.evidence
      ? { value: d.pollination.value, source: cite(d.pollination.evidence), ...(d.pollination.notes ? { note: d.pollination.notes } : {}) }
      : null,
  };
}

export function loadDossiers() {
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = Object.fromEntries(loadDossiers().map((d) => [d.speciesId, harvestFromDossier(d)]));
  writeFileSync(out, [
    '// GENERATED by scripts/build-perennial-harvest.mjs from research/perennial-sources/*.json.',
    '// Do not edit by hand: correct the dossier and re-run the script. See lib/perennial-harvest.ts.',
    '',
    "import type { PerennialHarvest } from './perennial-harvest';",
    '',
    `export const PERENNIAL_HARVEST_DATA: Record<string, PerennialHarvest> = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n'));
  console.log(`wrote ${Object.keys(data).length} species to ${out}`);
}
